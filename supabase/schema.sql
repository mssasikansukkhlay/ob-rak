create or replace function private.current_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.profiles p
  where p.id = (select auth.uid())
$$;

create or replace function private.can_access_appointment(p_user_id uuid, p_counselor_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select auth.uid()) = p_user_id
    or private.current_role() = 'admin'
    or exists (
      select 1
      from public.counselors c
      where c.id = p_counselor_id
        and c.user_id = (select auth.uid())
    )
$$;

create or replace function private.can_view_profile(p_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select auth.uid()) = p_profile_id
    or private.current_role() = 'admin'
    or exists (
      select 1
      from public.appointments a
      join public.counselors c on c.id = a.counselor_id
      where a.user_id = p_profile_id
        and c.user_id = (select auth.uid())
    )
$$;

