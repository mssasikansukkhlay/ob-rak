create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  student_id text unique,
  name text not null,
  email text not null,
  role text not null default 'student' check (role in ('student', 'counselor', 'admin')),
  consent_privacy boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.counselors (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references public.profiles(id) on delete set null,
  display_name text not null,
  title text not null,
  specialties jsonb not null default '[]'::jsonb,
  bio text not null default '',
  meeting_modes jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.availability (
  id bigint generated by default as identity primary key,
  counselor_id uuid not null references public.counselors(id) on delete cascade,
  weekday integer not null check (weekday between 0 and 6),
  start_time time not null,
  end_time time not null,
  slot_minutes integer not null default 45 check (slot_minutes between 15 and 180),
  created_at timestamptz not null default now(),
  constraint availability_time_check check (end_time > start_time),
  constraint availability_unique unique (counselor_id, weekday, start_time, end_time)
);

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  counselor_id uuid not null references public.counselors(id) on delete restrict,
  appointment_date date not null,
  appointment_time time not null,
  duration_minutes integer not null default 45 check (duration_minutes between 15 and 180),
  mode text not null,
  topic text not null,
  note text not null default '',
  risk_level text not null default 'normal' check (risk_level in ('normal', 'concern', 'urgent', 'immediate')),
  status text not null default 'confirmed' check (status in ('pending', 'confirmed', 'completed', 'cancelled', 'no_show')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists appointments_active_slot_unique
  on public.appointments (counselor_id, appointment_date, appointment_time)
  where status in ('pending', 'confirmed');

create index if not exists appointments_user_idx on public.appointments(user_id, appointment_date);
create index if not exists appointments_counselor_idx on public.appointments(counselor_id, appointment_date);

create table if not exists public.mood_entries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  mood text not null,
  stress integer not null check (stress between 0 and 10),
  energy integer not null check (energy between 0 and 10),
  note text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists mood_entries_user_created_idx on public.mood_entries(user_id, created_at desc);

create table if not exists public.assessment_results (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  assessment_type text not null,
  score integer not null check (score >= 0),
  max_score integer not null check (max_score > 0 and score <= max_score),
  level text not null,
  answers jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists assessment_results_user_created_idx on public.assessment_results(user_id, created_at desc);

create table if not exists public.journal_entries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  title text not null,
  content text not null,
  mood text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists journal_entries_user_created_idx on public.journal_entries(user_id, created_at desc);

