create or replace function public.get_available_slots(
  p_counselor_id uuid,
  p_date date
)
returns table(slot_time text, duration integer)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_date is null or p_date < current_date or p_date > current_date + 60 then
    return;
  end if;

  return query
  select
    to_char(gs.slot_ts, 'HH24:MI') as slot_time,
    a.slot_minutes as duration
  from public.availability a
  join public.counselors c on c.id = a.counselor_id and c.active = true
  cross join lateral generate_series(
    p_date + a.start_time,
    p_date + a.end_time - make_interval(mins => a.slot_minutes),
    make_interval(mins => a.slot_minutes)
  ) as gs(slot_ts)
  where a.counselor_id = p_counselor_id
    and a.weekday = extract(dow from p_date)::integer
    and not exists (
      select 1
      from public.appointments ap
      where ap.counselor_id = p_counselor_id
        and ap.appointment_date = p_date
        and ap.appointment_time = gs.slot_ts::time
        and ap.status in ('pending', 'confirmed')
    )
  order by gs.slot_ts;
end;
$$;

revoke all on function public.get_available_slots(uuid, date) from public;
grant execute on function public.get_available_slots(uuid, date) to anon, authenticated;

create or replace function public.book_appointment(
  p_counselor_id uuid,
  p_date date,
  p_time time,
  p_mode text,
  p_topic text,
  p_note text default '',
  p_risk_level text default 'normal'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_duration integer;
  v_id uuid;
begin
  if v_user_id is null then
    raise exception 'กรุณาเข้าสู่ระบบก่อนจองนัด';
  end if;
  if private.current_role() <> 'student' then
    raise exception 'การจองนัดใช้สำหรับบัญชีนักศึกษา';
  end if;
  if p_risk_level = 'immediate' then
    raise exception 'ตอนนี้ควรติดต่อความช่วยเหลือเร่งด่วนก่อนการรอนัดหมาย';
  end if;
  if p_risk_level not in ('normal', 'concern', 'urgent', 'immediate') then
    raise exception 'ระดับการคัดกรองไม่ถูกต้อง';
  end if;
  if p_date < current_date or p_date > current_date + 60 then
    raise exception 'วันที่นัดหมายไม่อยู่ในช่วงที่เปิดจอง';
  end if;
  if coalesce(trim(p_mode), '') = '' or coalesce(trim(p_topic), '') = '' then
    raise exception 'กรอกข้อมูลการนัดหมายให้ครบ';
  end if;
  if not exists (
    select 1 from public.counselors c
    where c.id = p_counselor_id
      and c.active = true
      and c.meeting_modes ? p_mode
  ) then
    raise exception 'ผู้ให้คำปรึกษาหรือรูปแบบการพูดคุยไม่ถูกต้อง';
  end if;

  select s.duration into v_duration
  from public.get_available_slots(p_counselor_id, p_date) s
  where s.slot_time = to_char(current_date + p_time, 'HH24:MI')
  limit 1;

  if v_duration is null then
    raise exception 'ช่วงเวลานี้ไม่ว่างแล้ว กรุณาเลือกเวลาใหม่';
  end if;

  insert into public.appointments (
    user_id, counselor_id, appointment_date, appointment_time,
    duration_minutes, mode, topic, note, risk_level, status
  ) values (
    v_user_id, p_counselor_id, p_date, p_time,
    v_duration, trim(p_mode), trim(p_topic), left(coalesce(p_note, ''), 1200),
    coalesce(nullif(p_risk_level, ''), 'normal'), 'confirmed'
  ) returning id into v_id;

  return v_id;
exception
  when unique_violation then
    raise exception 'ช่วงเวลานี้มีผู้จองแล้ว กรุณาเลือกเวลาใหม่';
end;
$$;

revoke all on function public.book_appointment(uuid, date, time, text, text, text, text) from public;
grant execute on function public.book_appointment(uuid, date, time, text, text, text, text) to authenticated;

create or replace function public.reschedule_appointment(
  p_appointment_id uuid,
  p_date date,
  p_time time
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_counselor_id uuid;
  v_duration integer;
begin
  select a.counselor_id into v_counselor_id
  from public.appointments a
  where a.id = p_appointment_id
    and a.user_id = v_user_id
    and a.status in ('pending', 'confirmed');

  if v_counselor_id is null then
    raise exception 'ไม่พบนัดหมายของคุณหรือไม่สามารถเลื่อนนัดนี้ได้';
  end if;
  if p_date < current_date or p_date > current_date + 60 then
    raise exception 'วันที่นัดหมายไม่อยู่ในช่วงที่เปิดจอง';
  end if;

  select s.duration into v_duration
  from public.get_available_slots(v_counselor_id, p_date) s
  where s.slot_time = to_char(current_date + p_time, 'HH24:MI')
  limit 1;

  if v_duration is null then
    raise exception 'ช่วงเวลานี้ไม่ว่างแล้ว';
  end if;

  update public.appointments
  set appointment_date = p_date,
      appointment_time = p_time,
      duration_minutes = v_duration
  where id = p_appointment_id;
exception
  when unique_violation then
    raise exception 'ช่วงเวลานี้มีผู้จองแล้ว';
end;
$$;

revoke all on function public.reschedule_appointment(uuid, date, time) from public;
grant execute on function public.reschedule_appointment(uuid, date, time) to authenticated;

create or replace function public.cancel_appointment(p_appointment_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_row public.appointments%rowtype;
begin
  select * into v_row from public.appointments where id = p_appointment_id;
  if v_row.id is null then
    raise exception 'ไม่พบนัดหมาย';
  end if;

  if not private.can_access_appointment(v_row.user_id, v_row.counselor_id) then
    raise exception 'ไม่มีสิทธิ์ยกเลิกนัดนี้';
  end if;

  if v_row.status not in ('pending', 'confirmed') then
    raise exception 'นัดหมายนี้ไม่สามารถยกเลิกได้';
  end if;

  update public.appointments
  set status = 'cancelled'
  where id = p_appointment_id;
end;
$$;

revoke all on function public.cancel_appointment(uuid) from public;
grant execute on function public.cancel_appointment(uuid) to authenticated;

create or replace function public.update_appointment_status(
  p_appointment_id uuid,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.appointments%rowtype;
  v_role text := private.current_role();
begin
  if p_status not in ('confirmed', 'completed', 'cancelled', 'no_show') then
    raise exception 'สถานะไม่ถูกต้อง';
  end if;

  select * into v_row from public.appointments where id = p_appointment_id;
  if v_row.id is null then
    raise exception 'ไม่พบนัดหมาย';
  end if;

  if v_role = 'admin' then
    null;
  elsif v_role = 'counselor' and exists (
    select 1 from public.counselors c
    where c.id = v_row.counselor_id and c.user_id = (select auth.uid())
  ) then
    null;
  else
    raise exception 'ไม่มีสิทธิ์แก้ไขสถานะนัดนี้';
  end if;

  update public.appointments
  set status = p_status
  where id = p_appointment_id;
end;
$$;

revoke all on function public.update_appointment_status(uuid, text) from public;
grant execute on function public.update_appointment_status(uuid, text) to authenticated;

create or replace function public.admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if private.current_role() <> 'admin' then
    raise exception 'ไม่มีสิทธิ์ดูข้อมูลส่วนนี้';
  end if;

  select jsonb_build_object(
    'students', (select count(*) from public.profiles where role = 'student'),
    'upcoming', (select count(*) from public.appointments where status in ('pending', 'confirmed') and appointment_date >= current_date),
    'completed', (select count(*) from public.appointments where status = 'completed'),
    'assessments', (select count(*) from public.assessment_results),
    'topics', coalesce((
      select jsonb_agg(jsonb_build_object('topic', topic, 'count', total) order by total desc)
      from (
        select topic, count(*) as total
        from public.appointments
        group by topic
        order by total desc
        limit 5
      ) t
    ), '[]'::jsonb)
  ) into result;

  return result;
end;
$$;

revoke all on function public.admin_stats() from public;
grant execute on function public.admin_stats() to authenticated;

